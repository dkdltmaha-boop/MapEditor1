    private static bool RequireFile(string path)
    {
        if (File.Exists(path) && new FileInfo(path).Length > 0)
        {
            return true;
        }

        Debug.LogError("MapEditor export smoke test missing required file: " + path);
        return false;
    }

    private static bool RequireDirectory(string path)
    {
        if (Directory.Exists(path))
        {
            return true;
        }

        Debug.LogError("MapEditor export smoke test missing required folder: " + path);
        return false;
    }

    private static bool RequireJsonText(string json, string fileName, string expectedText)
    {
        if (!string.IsNullOrEmpty(json) && json.Contains(expectedText))
        {
            return true;
        }

        Debug.LogError("MapEditor export smoke test missing expected text in " + fileName + ": " + expectedText);
        return false;
    }

    private static void Require(bool condition, string message)
    {
        if (!condition)
        {
            throw new InvalidOperationException(message);
        }
    }
